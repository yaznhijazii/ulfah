export interface PartnerStatus {
    mood: string | null;
    lastNote?: string | null;
}

export const getAIRecommendation = (status: PartnerStatus): { title: string; advice: string } => {
    const { mood, lastNote } = status;
    
    // Date-based seed to ensure the tip changes daily but stays consistent for the day
    const getDayIndex = (max: number) => {
        const today = new Date();
        const seed = today.getFullYear() * 1000 + (today.getMonth() + 1) * 100 + today.getDate();
        return seed % max;
    };

    if (mood === 'sad') {
        const sadTips = [
            'يبدو أن شريكك يمر بوقت عصيب. جرب إرسال رسالة صوتية دافئة أو عرض عليه جلسة استماع دون مقاطعة.',
            'الحزن يحتاج إلى احتواء. أخبر شريكك أنك بجانبه مهما حدث، وأن مشاعره مقدرة ومسموعة.',
            'جرب أن تترك لشريكك مساحة، لكن ذكّره بكلمة بسيطة أنك "هنا" عندما يحتاج للتحدث.'
        ];
        return {
            title: 'لمسة مواساة 🕊️',
            advice: sadTips[getDayIndex(sadTips.length)]
        };
    }

    if (mood === 'tired') {
        const tiredTips = [
            'شريكك يشعر بالإرهاق. ما رأيك بتجهيز مشروبه المفضل أو القيام بعمل صغير من مهامه ليتمكن من الراحة؟',
            'في زحمة التعب، كلمة "يعطيك العافية" لها سحر خاص. جرب قولها بصدق مع لمسة حانية.',
            'اقترح على شريكك وقتاً مستقطعاً من كل شيء لتستمتعا بهدوء الصمت معاً.'
        ];
        return {
            title: 'ملاذ الراحة ☕',
            advice: tiredTips[getDayIndex(tiredTips.length)]
        };
    }

    if (mood === 'happy') {
        const happyTips = [
            'مزاج شريكك رائع! استغل اللحظة لمشاركته ذكرى سعيدة أو التخطيط لمغامرة بسيطة في نهاية الأسبوع.',
            'الفرح معدٍ! احتفلا بلحظة السعادة هذه، ربما بوجبة خفيفة تحبانها أو أغنية تذكركما ببداياتكما.',
            'عندما يكون الشريك سعيداً، تكون الأذن أكثر استعداداً لسماع كلمات الحب العميقة. عبّر عما في قلبك!'
        ];
        return {
            title: 'مضاعفة الفرح 🌟',
            advice: happyTips[getDayIndex(happyTips.length)]
        };
    }

    if (lastNote && lastNote.length > 50) {
        return {
            title: 'صدى الكلمات ✍️',
            advice: 'شريكك كتب لك خاطرة عميقة مؤخراً. حاول قراءتها بتمعن والرد عليها بكلمة صادقة تظهر تقديرك لمشاعره.'
        };
    }

    // Default pool for "Bithrat Mawadda" 🌱
    const genericTips = [
        'اليوم يوم هادئ. جرب أن تسأل شريكك عن شيء جديد تعلمه اليوم، أو ببساطة أخبره أنك تقدر وجوده في حياتك.',
        'ما رأيك بتخصيص 15 دقيقة اليوم للحديث عن "أجمل صفة" رأيتها في شريكك هذا الأسبوع؟',
        'التقدير في التفاصيل! فاجئ شريكك بذكر موقف صغير فعله نال إعجابك، ستفاجأ بحجم أثره.',
        'جرب أن ترسل لشريكك صورة لذكرى قديمة جمعتكم الآن مع رسالة: "اشتقنا لتلك اللحظات".',
        'هل سألت شريكك اليوم: "كيف يمكنني أن أجعل يومك أفضل؟" هذه الجملة تفتح أبواباً مغلقة.',
        'بادر اليوم بعمل محبب لشريكك كان قد طلبه منك سابقاً ونسيته في زحمة الحياة.',
        'خطط لعشاء بسيط في المنزل اليوم مع إضاءة خافتة، بعيداً عن الهواتف وشاشات التلفزيون.',
        'أخبر شريكك اليوم عن "حلم" تريد تحقيقه معه في السنوات الخمس القادمة.',
        'كلمة "شكراً" على الأشياء الروتينية التي يقوم بها الشريك بانتظام تعيد شحن طاقة الود.'
    ];

    return {
        title: 'بذرة مودة 🌱',
        advice: genericTips[getDayIndex(genericTips.length)]
    };
};
